import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const ROOT = resolve('.');
const SOURCE = join(ROOT, 'src');
const OUT_DIR = join(ROOT, 'docs', 'graphs');
const IMPORT_PATTERN = /^(?:import|export)\s[^'"]*?from\s+['"](\.[^'"]+)['"]/gm;
const LAYERS = Object.freeze(['config', 'domain', 'infrastructure', 'application', 'http']);

const walk = dir => readdirSync(dir).flatMap(name => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : path.endsWith('.mjs') ? [path] : [];
});

const id = path => relative(SOURCE, path).replaceAll('\\', '/');
const nodeName = path => id(path).replace(/[^\w]/g, '_');
const layerOf = path => LAYERS.find(layer => id(path).startsWith(`${layer}/`)) ?? 'entry';

const files = walk(SOURCE);
const edges = files.flatMap(file =>
  [...readFileSync(file, 'utf8').matchAll(IMPORT_PATTERN)].map(match => [file, resolve(dirname(file), match[1])])
);

const groups = [...LAYERS, 'entry'].map(layer => {
  const members = files.filter(file => layerOf(file) === layer).map(file => `    ${nodeName(file)}["${id(file)}"]`);
  return members.length ? [`  subgraph ${layer}`, ...members, '  end'].join('\n') : '';
}).filter(Boolean);

const mermaid = ['```mermaid', 'flowchart LR', ...groups, ...edges.map(([from, to]) => `  ${nodeName(from)} --> ${nodeName(to)}`), '```'].join('\n');

const fanIn = files.map(file => [id(file), edges.filter(([, to]) => to === file).length]).sort((a, b) => b[1] - a[1]);
const table = ['| Module | Imported by |', '|---|---|', ...fanIn.map(([name, count]) => `| \`${name}\` | ${count} |`)].join('\n');

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, 'module-graph.md'), [
  '# Module graph (generated by `npm run graph`)', '',
  'Dependencies point inward: http → application → domain, with infrastructure behind repositories and config shared.', '',
  mermaid, '', '## Fan-in (who would be affected by a change)', '', table, ''
].join('\n'));
writeFileSync(join(OUT_DIR, 'module-graph.json'), JSON.stringify({ nodes: files.map(id), edges: edges.map(([f, t]) => [id(f), id(t)]) }, null, 2));
process.stdout.write(`graph: ${files.length} modules, ${edges.length} edges\n`);
